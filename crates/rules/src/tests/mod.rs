mod chests; // 무기 상자: 낮마다 놓이는 자리와 내용, 씨앗, 막는 타일, 지키는 몬스터, 밤에 사라지는 것
mod combat; // 검의 공격: 범위, 부채꼴, 쿨다운
mod days; // 낮과 밤, 밤의 무리와 등장하는 자리, 새벽, 성공과 새 원정
