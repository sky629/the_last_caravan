mod expedition; // 성공과 실패, 새 원정, 입장과 퇴장
mod guards; // 낮의 몬스터: 놓이는 자리, 자리를 지키고 쫓다가 돌아가기, 밤이 되면 마차로 향하기
mod hitscan; // 소총: 누른 Tick에 처음 닿는 몬스터 한 마리, 막힌 타일과 사거리, 사격 선이 끝난 자리
mod loot; // 바닥의 무기: 줍기와 맞바꾸기, 상자에서 나온 무기가 사라지지도 늘지도 않는 것, 시작 무기가 바닥에 놓이지 않는 것, 퇴장과 새 원정에서의 무기, F의 안내
mod monsters; // 몬스터의 목표 선택, 이동 경로, 공격
mod movement; // 장애물과 맵 경계, 이동 속도, 입력 보정
mod opening; // 상자 열기: 누르고 있는 시간, 여는 동안 하지 못하는 일, 진행이 돌아가는 경우, F의 우선순위, 두 명이 여는 경우, 안내
mod paths; // 몬스터가 걷는 길: 좁은 통로, 걸어서 가까운 감시탑
mod perf; // 몬스터 300마리와 감시탑 상한에서 Tick 하나의 계산 시간 (시간의 한계는 릴리스 빌드에서만 확인)
mod piercing; // 여러 마리를 맞히는 탄환: 닿는 순서대로 맞히고 정해진 수에서 사라지는 것, 같은 몬스터를 두 번 맞히지 않는 것, 막힌 타일과 사거리의 끝
mod projectiles; // 활의 탄환: 날아가는 속도, 처음 닿는 몬스터, 막힌 타일, 사거리, 한 Tick에 건너뛰지 않는 명중 판정
mod racks; // 야영지의 무기 진열대: 집으면 진열대는 그대로이고 든 무기는 사라지는 것, 이미 가진 무기, 바닥의 무기와의 우선순위, 안내
mod recovery; // 마차 곁의 회복, 마차의 수리, F의 대상 순서
mod resources; // 자원: 채집, 마차에 넣기, 떨어뜨리기와 줍기, 낮마다 다시 채우기, 총량
mod revive; // 쓰러짐, 부활, 출혈
mod sprint; // 달리기: 속도, 게이지가 줄고 차는 때, 달릴 수 없는 상태, 게이지가 가득 차는 때
mod towers; // 감시탑의 사격, 파괴, 수리
mod tuning; // 기본 수치가 충돌 처리의 전제를 지키는지
mod weapons; // 무기: 처음 드는 무기, 쓰러짐과 새 날과 새 원정에서의 무기
